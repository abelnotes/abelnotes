/// A straight run of [length] page units ending where [tail] starts.
List<StrokePoint> _lineInto(List<(int, double, double)> tail, double length) {
  final (_, ex, ey) = tail.first;
  final pts = <StrokePoint>[];
  const n = 60;
  for (var i = 0; i < n; i++) {
    final f = i / n;
    pts.add(StrokePoint(x: ex - length * (1 - f), y: ey, timestamp: i * 4));
  }
  for (final (t, x, y) in tail) {
    pts.add(StrokePoint(x: x, y: y, timestamp: n * 4 + t));
  }
  return pts;
}

ShapeData? _recognize(List<StrokePoint> pts) =>
    recognizeShape(pts, color: 0xFF000000, strokeWidth: 2);

void main() {
  for (final length in [40.0, 60.0, 100.0, 200.0]) {
    test('a held pen line of $length units is still a line', () {
      for (final tail in _tails) {
        final shape = _recognize(_lineInto(tail, length));
        expect(shape?.shapeType, 'line');
      }
    });
  }

  test('a line without a pause is unaffected', () {
    final pts = [
      for (var i = 0; i <= 50; i++)
        StrokePoint(x: 10.0 + i * 2, y: 20.0 + i * 0.1, timestamp: i * 4),
    ];
    final shape = _recognize(pts);
    expect(shape?.shapeType, 'line');
    expect(shape!.x1, closeTo(10, 1));
    expect(shape.x2, closeTo(110, 1));
  });
}
